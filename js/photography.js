/* ============================================================================
   photography.js — Exposures.
   ----------------------------------------------------------------------------
   Two photo sources, in order of preference:
     1. window.PHOTOS — generated by scripts/sync-instagram.py from the owner's
        Instagram feed. Local files under photography/img/, same origin.
     2. DATA.photography.photos — the owner-curated Cloudinary list. When no
        cloud name is configured these render as honest PENDING UPLOAD plates
        (no <img>, so no broken network request).

   All items are normalised by resolvePhotos() into one internal shape:
     { sources, ratio, caption, exif, date, permalink, generated }
   `sources` is {src, large, srcset, sizes, blur} or null for a pending plate.

   Rules: no HTML parsing (text via textContent/el()), every URL passes
   safeUrl(), optional fields that are absent render nothing.
   ========================================================================== */

import { D, el, extLink, safeUrl, monthIndex } from "./core.js";

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

const GENERATED_HEADING = "PENDING UPLOAD";

/* ============================================================================
   RESOLUTION — pure: given (window.PHOTOS, DATA) returns the render list.
   ========================================================================== */

/** Width/height ratio, constrained to something sane. */
function normaliseRatio(value) {
  const ratio = Number(value);
  return Number.isFinite(ratio) && ratio >= 0.2 && ratio <= 5 ? ratio : 1.5;
}

/** "YYYY-MM" or an ISO timestamp → "Mar 2026"; "" when unreadable. */
function monthLabel(value) {
  if (typeof value !== "string") return "";
  const match = /^(\d{4}-\d{2})/.exec(value.trim());
  if (!match) return "";
  const index = monthIndex(match[1]);
  if (index === null) return "";
  return `${MONTHS[index % 12]} ${Math.floor(index / 12)}`;
}

/** Kept only when it is an https Instagram permalink. */
function instagramPermalink(value) {
  const url = safeUrl(value);
  if (!url || !/^https:\/\/(www\.)?instagram\.com\//i.test(url)) return null;
  return url;
}

/** A Cloudinary cloud name is a host label, so keep it to host-safe chars. */
function cloudNameOf(photography) {
  const cloud = photography && typeof photography.cloudName === "string"
    ? photography.cloudName.trim()
    : "";
  if (!cloud || cloud === "your-cloud-name") return "";
  return /^[A-Za-z0-9_-]+$/.test(cloud) ? cloud : "";
}

function cloudUrl(cloud, publicId, width, extra = "") {
  return `https://res.cloudinary.com/${cloud}` +
         `/image/upload/f_auto,q_auto,w_${width},c_limit${extra}/${publicId}`;
}

/**
 * Sources for a local (Instagram-sync) photo. Only same-origin paths are
 * accepted: a scheme (https:, mailto:, …), "..", backslash, query or fragment
 * means the item is dropped rather than rendered.
 */
function localSources(item) {
  const raw = typeof item.src === "string" ? item.src.trim() : "";
  if (!raw || raw.includes("..") || raw.includes("\\")) return null;
  if (raw.startsWith("#") || raw.startsWith("?")) return null;
  const url = safeUrl(raw);
  if (!url) return null;
  if (/^[a-z][a-z0-9+.-]*:/i.test(url)) return null; // remote URLs are not local
  return { src: url, large: url, srcset: null, sizes: null, blur: null };
}

/** Sources for a Cloudinary entry, or null when no image can be resolved. */
function cloudSources(item, cloud) {
  if (!item || typeof item.publicId !== "string") return null;
  const publicId = item.publicId.trim();
  if (!publicId || publicId.includes("\\") || publicId.includes("..")) return null;

  // A publicId may itself be a full URL or a root-relative path.
  if (/^(https?:\/\/|\/)/i.test(publicId)) {
    const url = safeUrl(publicId);
    if (!url || !/^(https:\/\/|\/)/i.test(url)) return null;
    return { src: url, large: url, srcset: null, sizes: null, blur: null };
  }

  if (!cloud) return null;
  return {
    src: cloudUrl(cloud, publicId, 1200),
    large: cloudUrl(cloud, publicId, 1600),
    srcset: [480, 800, 1200, 1600]
      .map((width) => `${cloudUrl(cloud, publicId, width)} ${width}w`)
      .join(", "),
    sizes: "(max-width: 599px) 92vw, (max-width: 959px) 46vw, 300px",
    blur: cloudUrl(cloud, publicId, 60, ",e_blur:800,q_1"),
  };
}

function text(value) {
  return typeof value === "string" ? value.trim() : "";
}

function resolveGenerated(item) {
  if (!item || typeof item !== "object") return null;
  const sources = localSources(item);
  if (!sources) return null; // drop invalid generated items
  return {
    sources,
    ratio: normaliseRatio(item.ratio),
    caption: text(item.caption),
    exif: "",
    date: text(item.date),
    permalink: instagramPermalink(item.permalink),
    generated: true,
  };
}

function resolveCloudinary(item, photography) {
  if (!item || typeof item !== "object") return null;
  return {
    sources: cloudSources(item, cloudNameOf(photography)),
    ratio: normaliseRatio(item.ratio),
    caption: text(item.caption),
    exif: text(item.exif),
    date: "",
    permalink: null,
    generated: false,
  };
}

/**
 * Pure resolver used by render().
 *
 * @param {Array|null} generated  window.PHOTOS (may be absent/empty)
 * @param {object|null} data      window.DATA (or a photography object)
 * @returns {Array<object>}       normalised photo records
 */
export function resolvePhotos(generated, data) {
  const photography = (data && data.photography) || data || {};

  if (Array.isArray(generated) && generated.length > 0) {
    return generated.map(resolveGenerated).filter(Boolean);
  }

  const list = Array.isArray(photography.photos) ? photography.photos : [];
  return list.map((item) => resolveCloudinary(item, photography)).filter(Boolean);
}

/* ============================================================================
   RENDER
   ========================================================================== */

function pendingLabel() {
  return el("span", "plate-pending-label mono", GENERATED_HEADING);
}

function separator() {
  return document.createTextNode(" \u00B7 ");
}

/** "01", "02", … for the mono reading line. */
function plateNumber(index) {
  return String(index + 1).padStart(2, "0");
}

/** The reading line: index · (EXIF | date · permalink). */
function captionMeta(photo, index) {
  const meta = el("span", "plate-meta mono");
  meta.append(el("span", "plate-num", plateNumber(index)));

  if (photo.generated) {
    const label = monthLabel(photo.date);
    if (label) {
      const time = el("time", "plate-date", label);
      time.setAttribute("datetime", photo.date);
      meta.append(separator(), time);
    }
    if (photo.permalink) {
      const link = extLink("plate-link", "View on Instagram", photo.permalink);
      if (link) meta.append(separator(), link);
    }
  } else if (photo.exif) {
    meta.append(separator(), el("span", "plate-exif", photo.exif));
  }

  return meta;
}

function captionBlock(photo, index) {
  const caption = el("figcaption", "plate-caption");
  caption.append(
    el("span", "plate-cap", photo.caption || "Untitled"),
    captionMeta(photo, index)
  );
  return caption;
}

/** One <li class="plate">. Real images get a <button>; pending plates do not. */
function plateFigure(photo, index, openers) {
  const item = el("li", "plate");
  const figure = el("figure", "plate-fig");

  const frame = el("span", "plate-frame");
  frame.style.setProperty("aspect-ratio", String(photo.ratio));

  const alt = photo.caption || "Untitled";

  if (photo.sources) {
    const button = el("button", "plate-open");
    button.type = "button";
    button.setAttribute("aria-label", `Open photograph: ${alt}`);

    const img = el("img", "plate-img");
    img.alt = alt;
    img.decoding = "async";
    img.loading = index > 2 ? "lazy" : "eager";

    if (photo.sources.blur) {
      frame.classList.add("is-blur");
      frame.style.setProperty("background-image", `url("${photo.sources.blur}")`);
      img.addEventListener("load", () => frame.classList.add("is-loaded"), { once: true });
    }

    // A local file that is missing becomes an honest pending plate instead of
    // a broken image, and the opener is disabled so the lightbox never shows it.
    img.addEventListener("error", () => {
      photo.broken = true;
      frame.replaceChildren(pendingLabel());
      frame.classList.remove("is-blur", "is-loaded");
      frame.classList.add("plate-pending");
      frame.style.removeProperty("background-image");
      button.disabled = true;
      button.classList.add("is-disabled");
      button.removeAttribute("aria-label");
    }, { once: true });

    img.src = photo.sources.src;
    if (photo.sources.srcset) {
      img.srcset = photo.sources.srcset;
      img.sizes = photo.sources.sizes;
    }

    frame.append(img);
    button.append(frame);
    figure.append(button);
    openers.set(index, button);
  } else {
    frame.classList.add("plate-pending");
    frame.append(pendingLabel());
    figure.append(frame);
  }

  figure.append(captionBlock(photo, index));
  item.append(figure);
  return item;
}

/* ---- page header --------------------------------------------------------- */

function renderSub(count) {
  const node = document.getElementById("photo-sub");
  if (!node) return;
  const photography = (D && D.photography) || {};
  const gear = text(photography.gear);
  const noun = count === 1 ? "frame" : "frames";
  node.textContent = gear ? `${count} ${noun} \u00B7 ${gear}` : `${count} ${noun}`;
}

/* ---- Instagram footer link ----------------------------------------------- */

const BARE_INSTAGRAM = /^https:\/\/(www\.)?instagram\.com\/?$/i;

function instagramLink() {
  const photography = (D && D.photography) || {};
  const url = safeUrl(photography.instagram);
  if (!url || BARE_INSTAGRAM.test(url)) return null;
  return extLink("plates-more-link mono", "Full stream on Instagram \u2192", url);
}

/* ============================================================================
   LIGHTBOX
   ========================================================================== */

function initLightbox(photos, openers) {
  const box = document.getElementById("lightbox");
  if (!box) return;
  const img = document.getElementById("lb-img");
  const cap = document.getElementById("lb-cap");
  const btnClose = document.getElementById("lb-close");
  const btnPrev = document.getElementById("lb-prev");
  const btnNext = document.getElementById("lb-next");
  if (!img || !cap || !btnClose || !btnPrev || !btnNext) return;

  let current = 0;
  let returnFocus = null;

  const viewable = () => photos
    .map((photo, index) => ({ photo, index }))
    .filter(({ photo }) => photo.sources && !photo.broken);

  function refreshNav() {
    const single = viewable().length < 2;
    btnPrev.hidden = single;
    btnNext.hidden = single;
    box.classList.toggle("is-single", single);
  }

  function show(position) {
    const list = viewable();
    if (!list.length) return;
    const pos = ((position % list.length) + list.length) % list.length;
    current = pos;
    const { photo } = list[pos];
    const caption = photo.caption || "Untitled";

    img.src = photo.sources.large || photo.sources.src;
    if (photo.sources.srcset) {
      img.srcset = photo.sources.srcset;
      img.sizes = "92vw";
    } else {
      img.removeAttribute("srcset");
      img.removeAttribute("sizes");
    }
    img.alt = caption;
    cap.textContent = `${caption}  ${pos + 1} / ${list.length}`;
    refreshNav();
  }

  function open(photoIndex) {
    const pos = viewable().findIndex(({ index }) => index === photoIndex);
    if (pos === -1) return;
    returnFocus = openers.get(photoIndex) || document.activeElement;
    show(pos);
    box.hidden = false;
    document.documentElement.classList.add("is-locked");
    btnClose.focus();
  }

  function close() {
    if (box.hidden) return;
    box.hidden = true;
    document.documentElement.classList.remove("is-locked");
    img.removeAttribute("src");
    img.removeAttribute("srcset");
    img.removeAttribute("sizes");
    img.alt = "";
    if (returnFocus && typeof returnFocus.focus === "function") returnFocus.focus();
  }

  btnClose.addEventListener("click", close);
  btnPrev.addEventListener("click", () => show(current - 1));
  btnNext.addEventListener("click", () => show(current + 1));

  box.addEventListener("click", (event) => {
    if (event.target === box) close();
  });

  document.addEventListener("keydown", (event) => {
    if (box.hidden) return;

    if (event.key === "Escape") {
      event.preventDefault();
      close();
      return;
    }
    if (event.key === "ArrowLeft") {
      event.preventDefault();
      show(current - 1);
      return;
    }
    if (event.key === "ArrowRight") {
      event.preventDefault();
      show(current + 1);
      return;
    }
    if (event.key !== "Tab") return;

    const focusables = [btnClose, btnPrev, btnNext].filter((node) => !node.hidden);
    if (!focusables.length) return;
    const at = focusables.indexOf(document.activeElement);
    event.preventDefault();
    let next;
    if (at === -1) {
      next = event.shiftKey ? focusables[focusables.length - 1] : focusables[0];
    } else {
      const step = event.shiftKey ? -1 : 1;
      next = focusables[(at + step + focusables.length) % focusables.length];
    }
    next.focus();
  });

  for (const { index } of viewable()) {
    const button = openers.get(index);
    if (!button) continue;
    button.addEventListener("click", () => open(index));
  }

  refreshNav();
}

/* ============================================================================
   ENTRY POINT
   ========================================================================== */

export function render() {
  if (!D || typeof document === "undefined") return;

  const generated = typeof window !== "undefined" ? window.PHOTOS : null;
  const photos = resolvePhotos(generated, D);

  renderSub(photos.length);

  const section = document.getElementById("plates");
  if (!section) return;

  const wrap = el("div", "wrap");
  section.replaceChildren(wrap);

  if (!photos.length) {
    wrap.append(el("p", "empty", "No exposures yet."));
  } else {
    const list = el("ul", "plates");
    const openers = new Map();
    photos.forEach((photo, index) => {
      list.append(plateFigure(photo, index, openers));
    });
    wrap.append(list);
    initLightbox(photos, openers);
  }

  const link = instagramLink();
  if (link) {
    const row = el("p", "plates-more");
    row.append(link);
    wrap.append(row);
  }
}
